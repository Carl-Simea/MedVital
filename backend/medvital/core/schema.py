"""Shared health observation schema and data-provenance model (schema version 1).

Every number MEDVITAL handles is a :class:`HealthObservation` carrying a mandatory
:class:`Provenance`. Provenance records whether the value is **simulated**,
**measured** or **modeled** — the three are never interchangeable.

This module is pure data definition + structural validation. Semantic validation
(is the metric known? is the unit canonical?) lives in ``core.module_spec``.
"""

from __future__ import annotations

import hashlib
import json
import re
from datetime import UTC
from enum import StrEnum
from typing import Annotated, Self
from uuid import UUID

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    field_validator,
    model_validator,
)

SCHEMA_VERSION = 1

# Identifiers are restricted so they are safe in URLs, IndexedDB keys and SQL text columns.
SubjectId = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9][A-Za-z0-9_.:-]{0,63}$")]
MetricId = Annotated[str, StringConstraints(pattern=r"^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$")]
ShortText = Annotated[str, StringConstraints(min_length=1, max_length=256)]
LongText = Annotated[str, StringConstraints(max_length=2000)]

_MAX_CONTEXT_ITEMS = 16
_MAX_CONTEXT_LEN = 128


class ModuleId(StrEnum):
    """The four independent health modules."""

    RADIATION = "radiation"
    BONE = "bone"
    CARDIOVASCULAR = "cardiovascular"
    BEHAVIORAL = "behavioral"


class DataOrigin(StrEnum):
    """What kind of thing a value is. Never merge across origins implicitly."""

    SIMULATED = "simulated"  # produced by MEDVITAL's synthetic generator; not real
    MEASURED = "measured"  # recorded by an instrument/person/dataset outside MEDVITAL
    MODELED = "modeled"  # computed by a documented method from other data


class Provenance(BaseModel):
    """Where a value came from. Requirements depend on ``data_origin``:

    * simulated: ``generator_version`` and ``seed`` required.
    * measured:  ``source_ref`` required (instrument, dataset id, DOI or URL a human can
      resolve); ``generator_version`` forbidden.
    * modeled:   ``method`` required (model/algorithm name and version);
      ``generator_version`` forbidden.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    data_origin: DataOrigin
    source: ShortText = Field(description="System, instrument or dataset family that produced the value.")
    source_ref: ShortText | None = Field(
        default=None, description="Resolvable reference: dataset accession, DOI, URL, instrument id."
    )
    method: ShortText | None = Field(default=None, description="Model or algorithm name + version.")
    generator_version: ShortText | None = None
    seed: int | None = None
    derived_from: tuple[UUID, ...] = Field(
        default=(), description="Observation ids this value was computed from (modeled data)."
    )
    license: ShortText | None = None
    retrieved_at: AwareDatetime | None = None
    notes: LongText | None = None

    @model_validator(mode="after")
    def _check_origin_requirements(self) -> Self:
        origin = self.data_origin
        if origin is DataOrigin.SIMULATED:
            if self.generator_version is None or self.seed is None:
                raise ValueError("simulated provenance requires generator_version and seed")
        elif origin is DataOrigin.MEASURED:
            if self.source_ref is None:
                raise ValueError("measured provenance requires source_ref")
            if self.generator_version is not None or self.seed is not None:
                raise ValueError("measured provenance must not carry generator_version or seed")
        elif origin is DataOrigin.MODELED:
            if self.method is None:
                raise ValueError("modeled provenance requires method")
            if self.generator_version is not None:
                raise ValueError("modeled provenance must not carry generator_version")
        return self


class HealthObservation(BaseModel):
    """One immutable observation of one metric for one subject at one time.

    Observations are append-only. A correction is a *new* observation whose
    ``supersedes`` points at the old id; nothing is ever updated in place. The ``id``
    is generated by the client (UUID) so offline creation and retried sync are idempotent.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: int = Field(default=SCHEMA_VERSION)
    id: UUID
    subject_id: SubjectId
    module: ModuleId
    metric: MetricId = Field(description="'<module>.<name>', e.g. 'bone.areal_bmd'.")
    value: float = Field(allow_inf_nan=False)
    unit: ShortText = Field(description="UCUM-style unit string. Must match the metric definition.")
    observed_at: AwareDatetime = Field(description="When the phenomenon was observed (UTC-normalised).")
    recorded_at: AwareDatetime = Field(description="When the client recorded it (UTC-normalised).")
    context: dict[str, str] = Field(default_factory=dict, description="Small qualifiers, e.g. {'site': ...}.")
    provenance: Provenance
    supersedes: UUID | None = None

    @field_validator("schema_version")
    @classmethod
    def _check_schema_version(cls, v: int) -> int:
        if v != SCHEMA_VERSION:
            raise ValueError(f"unsupported schema_version {v}; this server speaks {SCHEMA_VERSION}")
        return v

    @field_validator("observed_at", "recorded_at")
    @classmethod
    def _to_utc(cls, v):
        return v.astimezone(UTC)

    @field_validator("context")
    @classmethod
    def _check_context(cls, v: dict[str, str]) -> dict[str, str]:
        if len(v) > _MAX_CONTEXT_ITEMS:
            raise ValueError(f"context may hold at most {_MAX_CONTEXT_ITEMS} entries")
        key_re = re.compile(r"^[a-z][a-z0-9_]*$")
        for key, val in v.items():
            if not key_re.match(key):
                raise ValueError(f"context key {key!r} must match {key_re.pattern}")
            if not 0 < len(val) <= _MAX_CONTEXT_LEN:
                raise ValueError(f"context value for {key!r} must be 1..{_MAX_CONTEXT_LEN} characters")
        return v

    @model_validator(mode="after")
    def _check_metric_namespace(self) -> Self:
        if self.metric.split(".", 1)[0] != self.module.value:
            raise ValueError(f"metric {self.metric!r} does not belong to module {self.module.value!r}")
        if self.supersedes == self.id:
            raise ValueError("an observation cannot supersede itself")
        return self


def observation_fingerprint(observation: HealthObservation) -> str:
    """Stable content hash used for idempotent writes and conflict detection."""
    payload = observation.model_dump(mode="json")
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()
