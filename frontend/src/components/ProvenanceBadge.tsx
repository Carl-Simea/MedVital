import type { DataOrigin } from '../domain/observation'

const STYLES: Record<DataOrigin, { label: string; className: string; hint: string }> = {
  simulated: {
    label: 'Simulated',
    className: 'border-amber-500 bg-amber-50 text-amber-900',
    hint: 'Synthetic test data generated by MEDVITAL. Not real.',
  },
  measured: {
    label: 'Measured',
    className: 'border-emerald-600 bg-emerald-50 text-emerald-900',
    hint: 'Recorded by an instrument, person or dataset outside MEDVITAL.',
  },
  modeled: {
    label: 'Modeled',
    className: 'border-sky-600 bg-sky-50 text-sky-900',
    hint: 'Computed by a documented method from other data.',
  },
}

/** Always shows the origin as text (never colour alone) so it survives greyscale and screen readers. */
export function ProvenanceBadge({ origin }: { origin: DataOrigin }) {
  const s = STYLES[origin]
  return (
    <span
      title={s.hint}
      data-origin={origin}
      className={`inline-block rounded border px-2 py-0.5 text-xs font-semibold ${s.className}`}
    >
      {s.label}
    </span>
  )
}
